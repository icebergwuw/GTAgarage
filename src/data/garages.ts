function apt(n: number): GarageFloor[] {
  return [{ id: 'g', name: 'Garage', capacity: n }]
}

function g(
  row: Omit<Garage, 'floors' | 'capacity'> & { floors: GarageFloor[]; capacity?: number },
): Garage {
  const capacity = row.capacity ?? row.floors.reduce((sum, floor) => sum + floor.capacity, 0)
  return { ...row, capacity }
}


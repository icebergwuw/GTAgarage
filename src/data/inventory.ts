let n = 0
function car(
  model: string,
  garageId: string,
  floor: string,
  extra?: Partial<StoredVehicle>,
): StoredVehicle {
  n += 1
  return {
    uid: `sv-${n.toString().padStart(3, '0')}`,
    model,
    garageId,
    floor,
    ...extra,
  }
}

